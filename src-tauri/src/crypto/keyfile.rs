//! Keyfile generation and digesting (security model §3.1).
//!
//! A keyfile is either 32 CSPRNG bytes that shush generates, or any existing
//! file the user picks. Either way, only `SHA-256(file bytes)` enters the KDF.
//! The file is hashed in streaming fashion, so a huge file cannot exhaust
//! memory (issue #22).

use std::fs::OpenOptions;
use std::io::{Read, Write};
use std::path::Path;

use sha2::{Digest, Sha256};
use zeroize::{Zeroize, ZeroizeOnDrop, Zeroizing};

use super::zeroize_guard::KEY_LEN;
use super::{fill_random, CryptoError};

/// Random payload of a generated keyfile in bytes (256 bits).
pub const KEYFILE_LEN: usize = 32;

/// Magic prefix of keyfiles generated by shush.
pub const KEYFILE_MAGIC: &[u8; 8] = b"SHUSHKEY";
/// Current generated-keyfile format version.
pub const KEYFILE_VERSION: u8 = 1;
const CHECKSUM_LEN: usize = 4;
/// Total size of a generated keyfile: `magic || version || random || checksum`.
pub const GENERATED_FILE_LEN: usize = 8 + 1 + KEYFILE_LEN + CHECKSUM_LEN;

/// What a candidate keyfile is, as far as shush can tell.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum KeyfileKind {
    /// A shush-generated keyfile whose checksum verified.
    Generated,
    /// Any other file. A single changed byte locks the vault out.
    Arbitrary,
}

/// Builds the bytes of a generated keyfile (self-describing, checksummed).
fn encode_generated(random: &[u8; KEYFILE_LEN]) -> Zeroizing<Vec<u8>> {
    let mut out = Zeroizing::new(Vec::with_capacity(GENERATED_FILE_LEN));
    out.extend_from_slice(KEYFILE_MAGIC);
    out.push(KEYFILE_VERSION);
    out.extend_from_slice(random);
    let sum = Sha256::digest(out.as_slice());
    out.extend_from_slice(&sum[..CHECKSUM_LEN]);
    out
}

/// Classifies keyfile bytes. A file that carries the shush magic must be
/// intact: corruption is reported before the (slow) KDF runs, so the user can
/// tell "damaged keyfile" apart from "wrong password".
pub fn classify(bytes: &[u8]) -> Result<KeyfileKind, CryptoError> {
    if !bytes.starts_with(KEYFILE_MAGIC) {
        return Ok(KeyfileKind::Arbitrary);
    }
    if bytes.len() != GENERATED_FILE_LEN || bytes[8] != KEYFILE_VERSION {
        return Err(CryptoError::KeyfileCorrupt);
    }
    let (body, check) = bytes.split_at(GENERATED_FILE_LEN - CHECKSUM_LEN);
    if Sha256::digest(body)[..CHECKSUM_LEN] != *check {
        return Err(CryptoError::KeyfileCorrupt);
    }
    Ok(KeyfileKind::Generated)
}

const READ_CHUNK: usize = 64 * 1024;

/// `SHA-256(keyfile bytes)`, wiped on drop and redacted in `Debug`.
///
/// Limitation: `sha2` 0.10 does not zeroize its internal block buffer, so up
/// to 64 bytes of the keyfile's tail can remain in freed stack memory.
#[derive(Zeroize, ZeroizeOnDrop)]
pub struct KeyfileDigest([u8; KEY_LEN]);

impl KeyfileDigest {
    /// Borrows the digest bytes.
    pub fn expose(&self) -> &[u8; KEY_LEN] {
        &self.0
    }

    fn from_hasher(hasher: Sha256) -> Self {
        let mut out = Self([0u8; KEY_LEN]);
        hasher.finalize_into((&mut out.0).into());
        out
    }
}

impl core::fmt::Debug for KeyfileDigest {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.write_str("KeyfileDigest([REDACTED])")
    }
}

/// Generates fresh keyfile contents: 32 bytes from the OS CSPRNG.
pub fn generate() -> Result<Zeroizing<[u8; KEYFILE_LEN]>, CryptoError> {
    let mut bytes = Zeroizing::new([0u8; KEYFILE_LEN]);
    fill_random(bytes.as_mut())?;
    Ok(bytes)
}

/// Generates a new keyfile at `path` and returns its digest.
///
/// The file is created with `create_new`, so an existing file (perhaps an
/// existing keyfile!) is **never** overwritten. Data is flushed to disk before
/// returning.
pub fn create_keyfile(path: &Path) -> Result<KeyfileDigest, CryptoError> {
    let random = generate()?;
    let bytes = encode_generated(&random);
    let mut file = OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(path)
        .map_err(|e| CryptoError::KeyfileIo(e.kind()))?;
    let written = file.write_all(&bytes).and_then(|()| file.sync_all());
    if let Err(e) = written {
        drop(file);
        // Best effort: do not leave a partial keyfile that looks valid.
        let _ = std::fs::remove_file(path);
        return Err(CryptoError::KeyfileIo(e.kind()));
    }
    digest_bytes(&bytes)
}

/// Digests in-memory keyfile contents.
pub fn digest_bytes(bytes: &[u8]) -> Result<KeyfileDigest, CryptoError> {
    if bytes.is_empty() {
        return Err(CryptoError::EmptyKeyfile);
    }
    let mut hasher = Sha256::new();
    hasher.update(bytes);
    Ok(KeyfileDigest::from_hasher(hasher))
}

/// Digests a keyfile from any reader, in chunks of 64 KiB.
pub fn digest_reader<R: Read>(mut reader: R) -> Result<KeyfileDigest, CryptoError> {
    let mut hasher = Sha256::new();
    let mut buf = Zeroizing::new(vec![0u8; READ_CHUNK]);
    let mut total: u64 = 0;
    // Generated keyfiles are tiny; only the first few hundred bytes are ever
    // needed to verify one, so a huge file is still streamed, never buffered.
    let mut head = Zeroizing::new(Vec::<u8>::new());
    loop {
        let n = match reader.read(&mut buf) {
            Ok(0) => break,
            Ok(n) => n,
            Err(e) if e.kind() == std::io::ErrorKind::Interrupted => continue,
            Err(e) => return Err(CryptoError::KeyfileIo(e.kind())),
        };
        hasher.update(&buf[..n]);
        total += n as u64;
        if head.len() <= GENERATED_FILE_LEN {
            let take = (GENERATED_FILE_LEN + 1 - head.len()).min(n);
            head.extend_from_slice(&buf[..take]);
        }
    }
    if total == 0 {
        return Err(CryptoError::EmptyKeyfile);
    }
    classify(&head)?;
    Ok(KeyfileDigest::from_hasher(hasher))
}

/// Reads the first bytes of `path` and classifies it (see [`classify`]).
pub fn inspect_file(path: &Path) -> Result<KeyfileKind, CryptoError> {
    let file = std::fs::File::open(path).map_err(|e| CryptoError::KeyfileIo(e.kind()))?;
    let mut head = Zeroizing::new(Vec::new());
    file.take(GENERATED_FILE_LEN as u64 + 1)
        .read_to_end(&mut head)
        .map_err(|e| CryptoError::KeyfileIo(e.kind()))?;
    classify(&head)
}

/// Opens and digests the keyfile at `path`.
pub fn digest_file(path: &Path) -> Result<KeyfileDigest, CryptoError> {
    let file = std::fs::File::open(path).map_err(|e| CryptoError::KeyfileIo(e.kind()))?;
    digest_reader(std::io::BufReader::with_capacity(READ_CHUNK, file))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::io::ErrorKind;

    #[test]
    fn sha256_known_answer() {
        // FIPS 180-2 test vector "abc".
        let d = digest_bytes(b"abc").unwrap();
        assert_eq!(
            hex::encode(d.expose()),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
    }

    #[test]
    fn generated_random_payload_is_32_random_bytes() {
        let a = generate().unwrap();
        let b = generate().unwrap();
        assert_eq!(a.len(), KEYFILE_LEN);
        assert_ne!(*a, *b);
        assert_ne!(*a, [0u8; KEYFILE_LEN]);
    }

    #[test]
    fn streaming_digest_matches_one_shot_across_chunk_boundaries() {
        let data: Vec<u8> = (0..(3 * READ_CHUNK + 17))
            .map(|i| (i * 31 % 251) as u8)
            .collect();
        let streamed = digest_reader(std::io::Cursor::new(&data)).unwrap();
        assert_eq!(streamed.expose(), digest_bytes(&data).unwrap().expose());
    }

    #[test]
    fn empty_keyfile_is_rejected() {
        assert_eq!(digest_bytes(b"").unwrap_err(), CryptoError::EmptyKeyfile);
        assert_eq!(
            digest_reader(std::io::empty()).unwrap_err(),
            CryptoError::EmptyKeyfile
        );
    }

    #[test]
    fn create_then_read_back() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("vault.key");
        let created = create_keyfile(&path).unwrap();

        assert_eq!(
            std::fs::metadata(&path).unwrap().len(),
            GENERATED_FILE_LEN as u64
        );
        assert_eq!(inspect_file(&path).unwrap(), KeyfileKind::Generated);
        assert_eq!(digest_file(&path).unwrap().expose(), created.expose());
    }

    #[test]
    fn create_never_overwrites_existing_file() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("vault.key");
        std::fs::write(&path, b"precious existing keyfile").unwrap();

        assert_eq!(
            create_keyfile(&path).unwrap_err(),
            CryptoError::KeyfileIo(ErrorKind::AlreadyExists)
        );
        assert_eq!(std::fs::read(&path).unwrap(), b"precious existing keyfile");
    }

    #[test]
    fn missing_keyfile_reports_not_found() {
        let dir = tempfile::tempdir().unwrap();
        let err = digest_file(&dir.path().join("absent.key")).unwrap_err();
        assert_eq!(err, CryptoError::KeyfileIo(ErrorKind::NotFound));
    }

    #[test]
    fn single_bit_change_changes_digest() {
        let mut data = vec![0u8; 32];
        let a = digest_bytes(&data).unwrap();
        data[31] ^= 1;
        assert_ne!(a.expose(), digest_bytes(&data).unwrap().expose());
    }

    #[test]
    fn debug_output_is_redacted() {
        assert_eq!(
            format!("{:?}", digest_bytes(b"x").unwrap()),
            "KeyfileDigest([REDACTED])"
        );
    }

    #[test]
    fn generated_file_detects_corruption_and_arbitrary_files_pass() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("v.key");
        create_keyfile(&path).unwrap();
        let good = std::fs::read(&path).unwrap();

        for i in 0..good.len() {
            let mut bad = good.clone();
            bad[i] ^= 1;
            std::fs::write(&path, &bad).unwrap();
            // Flipping a magic byte makes it an arbitrary file, anything else is corrupt.
            let expect = if i < KEYFILE_MAGIC.len() {
                Ok(KeyfileKind::Arbitrary)
            } else {
                Err(CryptoError::KeyfileCorrupt)
            };
            assert_eq!(inspect_file(&path), expect, "byte {i}");
            assert_eq!(
                digest_file(&path).map(|_| ()),
                expect.map(|_| ()),
                "byte {i}"
            );
        }
        // Truncated and extended generated files are corrupt too.
        std::fs::write(&path, &good[..good.len() - 1]).unwrap();
        assert_eq!(inspect_file(&path), Err(CryptoError::KeyfileCorrupt));
        let mut longer = good.clone();
        longer.push(0);
        std::fs::write(&path, &longer).unwrap();
        assert_eq!(
            digest_file(&path).map(|_| ()),
            Err(CryptoError::KeyfileCorrupt)
        );

        // Legacy raw 32-byte keyfiles remain valid arbitrary files.
        std::fs::write(&path, [9u8; 32]).unwrap();
        assert_eq!(inspect_file(&path).unwrap(), KeyfileKind::Arbitrary);
        assert!(digest_file(&path).is_ok());
    }
}
